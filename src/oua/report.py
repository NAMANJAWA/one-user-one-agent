def export_viewer_state(ctx, out_dir):
    """One JSON file per viewer: the durable state document plus its goal instances and actions with status."""
    os.makedirs(out_dir, exist_ok=True)
    goals = defaultdict(list)
    for g in ctx.memory.all_goals():
        goals[g['viewer_id']].append(g)
    n = 0
    for uid, state in ctx.memory.all_states():
        doc = dict(state)
        doc['goal_instances'] = goals.get(uid, [])
        doc['actions_detail'] = [{'action_id': a['action_id'], 'type': a['type'], 'status': s,
                                  'published_at': a.get('published_at'), 'send_at': a.get('send_at')}
                                 for a, s in ctx.memory.actions_for(uid)]
        with open(os.path.join(out_dir, uid + '.json'), 'w', encoding='utf-8') as f:
            json.dump(doc, f, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
        n += 1
    return n


def reason_category(d):
    r = d.get('no_action_reason') or ''
    s = d.get('status')
    if s == 'DUPLICATE_IGNORED':
        return 'duplicate trigger (same event id redelivered)'
    if r.startswith('stale trigger'):
        return 'stale trigger from offline buffer (viewer not in session)'
    if r.startswith('already acted in this session'):
        return 'already acted in this session (page still live)'
    if r.startswith('not worth an intervention'):
        return 'chosen: not worth an intervention (best goal scores below the floor)'
    if 'is still live until' in r and 'republishing it would add nothing' in r:
        return 'not a new choice: page for the same goal still live from an earlier visit (viewer still sees it)'
    if 'display dialect unknown' in r:
        return 'app dialect unknown (NA / missing): cannot know which page the app will request'
    if 'no titles exist in dialect' in r:
        return 'app dialect has no content (d7)'
    if r.startswith('no measurable goal'):
        return 'no measurable goal the viewer is eligible for'
    if s == 'BLOCKED' or r.startswith('independent checks'):
        return 'blocked by independent checks'
    if 'data store' in r:
        return 'data store unavailable and no safe fallback'
    if s == 'SHADOW_NO_ACTION' or r.startswith('holdout'):
        return 'holdout arm (shadow decision only)'
    if r.startswith('cannot show anything useful'):
        return 'no valid page could be built'
    return r[:80] or s


def _jl(path):
    return list(read_jsonl(path)) if os.path.exists(path) else []


