def write_html_viewer(ctx, run_dir):
    """A single self-contained HTML file to browse every viewer's timeline offline."""
    D = _jl(os.path.join(run_dir, 'decisions.jsonl'))
    O = _jl(os.path.join(run_dir, 'outcomes.jsonl'))
    A = {a['action_id']: a for a in _jl(os.path.join(run_dir, 'actions.jsonl'))}
    viewers = defaultdict(lambda: {'arm': None, 'items': [], 'tags': set()})
    for d in D:
        v = viewers[d['viewer_id']]
        v['arm'] = d['arm']
        g = d.get('goal') or {}
        item = {'t': d.get('published_at') or d.get('decided_at'), 'k': d['kind'], 'id': d['decision_id'],
                's': d['status'], 'a': d.get('action'), 'g': g.get('id'), 'c': d.get('confidence'),
                'cr': d.get('confidence_reason'), 'r': d.get('no_action_reason'),
                'dl': (d.get('dialect') or {}).get('used'), 'cf': (d.get('dialect') or {}).get('conflicts'),
                'm': (d.get('goal_selection') or {}).get('model', {}).get('outcome'),
                'ms': (d.get('latency') or {}).get('decided_in_ms'),
                'x': [A[a]['type'] for a in d.get('actions', []) if a in A],
                'ch': d.get('changes')}
        v['items'].append(item)
        v['tags'].add(d['status'])
        if d['kind'] == 'replan':
            v['tags'].add('REPLAN')
    for o in O:
        v = viewers[o['viewer_id']]
        v['items'].append({'t': o['judged_at'], 'k': 'outcome', 'id': o['goal_instance_id'], 's': o['status'],
                           'g': o['goal_id'], 'r': o.get('attribution'), 'l': [l['text'] for l in o.get('learned',
                                                                                                     [])]})
        v['tags'].add('OUTCOME_' + o['status'].upper())
    data = {u: {'arm': v['arm'], 'tags': sorted(v['tags']), 'items': sorted(v['items'], key=lambda i: i['t'] or '')}
            for u, v in sorted(viewers.items())}
    payload = json.dumps(data, separators=(',', ':')).replace('</', '<\\/')
    page = HTML.replace('__DATA__', payload).replace('__TITLE__', html.escape('Agent audit viewer'))
    with open(os.path.join(run_dir, 'audit_viewer.html'), 'w', encoding='utf-8') as f:
        f.write(page)


